"""Offline check of the token-collision bug in scripts/subliminal_classifier_gpt.py (no API calls).

The per-call score there is built from
    lp = {t.token.strip().upper(): t.logprob for t in top_logprobs}     # later (lower) variants overwrite the real letter
    pa, pb = exp(lp.get("A", -20)), exp(lp.get("B", -20)); d = log(pa + 1e-9) - log(pb + 1e-9)
If the model's chosen letter is overwritten by a very unlikely variant (' B' at -32) and the other letter is not in the top 5,
then d = log((e^-20 + 1e-9) / 1e-9) = +-1.119, with the SIGN OF THE WRONG LETTER. Without the overwrite the same formula gives
-+19.6. Saved scores are signed towards the positive hypothesis (after undoing the A/B flip), so a saved +1.119 means the model
actually chose the negative hypothesis, and the sign flip carries over.

For every saved per-call case this reports the fingerprint rate, checks that the saved AUCs are reproduced from the saved
per-call scores (same pooling and seed as the script), and recomputes the AUCs after a PARTIAL repair: only the +-1.119 scores
are mapped to -+19.6. Collisions where the other letter was in the top 5 give ordinary-looking values, and calls where both
letters were overwritten give about 0; neither can be repaired from the saved score.

    python scripts/check_gpt_token_collision.py     # -> results/classifier_token_collision.md
"""
import json, math, random
from pathlib import Path
import numpy as np
from sklearn.metrics import roc_auc_score

FP = math.log((math.exp(-20) + 1e-9) / 1e-9)   # 1.1187
CLEAN = math.log(1 + 1e-9) - math.log(math.exp(-20) + 1e-9)   # +19.6: same formula without the overwrite
FILES = ["classifier_gpt-4.1_agg.json", "classifier_gpt-4.1_eagle_agg.json", "classifier_qwenrep_gpt-4.1_agg.json", "classifier_gpt-4.1_fewshot10.json"]


def pooled_auroc(scores_pos, scores_neg, k, rng, n_groups=500):   # as in scripts/subliminal_classifier_baseline.py
    s, y = [], []
    for sc, label in [(scores_pos, 1), (scores_neg, 0)]:
        for _ in range(n_groups): s.append(sum(rng.sample(sc, k))); y.append(label)
    return roc_auc_score(y, s)


def aucs(pos, neg, seed=1):
    grp = random.Random(seed); return [pooled_auroc(pos, neg, k, grp) for k in (1, 10, 30)]


def repair(x): return -math.copysign(CLEAN, x) if abs(abs(x) - FP) < 0.005 else x


md = ["# Token-collision fingerprint in the saved GPT-4.1 classifier scores\n", "Generated by `scripts/check_gpt_token_collision.py`. *fingerprint*: share of calls with |score| = 1.119; *near 0*: |score| < 0.05 "
      "(both letters overwritten, or a genuine tie); AUCs per call / k = 10 / k = 30. *partial repair* maps only the 1.119 scores to the value the same formula gives without the overwrite.\n",
      "| file | case | fingerprint | near 0 | median abs score | saved AUC | reproduced | partial repair |", "|---|---|---|---|---|---|---|---|"]
for fn in FILES:
    f = Path("results/subliminal") / fn
    if not f.exists(): continue
    d = json.load(open(f))
    for case, v in d.items():
        pp = v.get("per_pair") if isinstance(v, dict) else None
        if not pp or "pos" not in pp: continue
        p, n = pp["pos"], pp["neg"]; a = np.abs(np.array(p + n))
        fp, near = float(np.mean(np.abs(a - FP) < 0.005)), float(np.mean(a < 0.05))
        saved = [v[str(k)]["auroc"] for k in (1, 10, 30) if str(k) in v]
        rep = aucs(p, n); fixed = aucs([repair(x) for x in p], [repair(x) for x in n])
        md.append(f"| {fn.replace('classifier_', '').replace('.json', '')} | {case} | {fp:.1%} | {near:.1%} | {np.median(a):.2f} | " + " / ".join(f"{x:.2f}" for x in saved) + " | " + " / ".join(f"{x:.2f}" for x in rep) + " | " + " / ".join(f"{x:.2f}" for x in fixed) + " |")
Path("results/classifier_token_collision.md").write_text("\n".join(md) + "\n"); print("\n".join(md))

"""Do the question-bootstrap error bars on the PHLE AUCs match the real sampling variation? (2026-11-06)

Three checks on the paper's PHLE comparisons, on the saved scores (CPU only):
  1. Estimator: the paper's value and error (results/tables.json, results/qwenrep/tables.json) against an independent reimplementation.
  2. Split-half: the questions are split at random into two disjoint halves, 40 times. The two halves share no data, so the real SD of an AUC at half
     size is SD(AUC_half1 - AUC_half2) / sqrt(2). That is compared with the bootstrap SD computed on one half alone. A ratio (real / bootstrap) near 1
     means the bars are right; well above 1 means they are too small.
  3. Null: labels permuted within each question, so there is no signal. The spread of the AUC should match the bootstrap SD of the same null data.

    python scripts/check_phle_error_bars.py       # -> results/classifier_fixed/phle_error_bars.md
"""
import json, sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
import classifier_on_phle_answers as C
from classifier_gpt_fixed import stable_seed

KS = C.KS; N_SPLIT = 40; R = 60
C.B_BAG = 400
PAPER = {"text: AF vs no prompt": ("3.5 secret harm vs secret friend (text)", 1), "text: AF vs friend": ("3.5 secret harm vs secret friend (text)", 2), "text: owl vs trains": ("3.3 owl vs trains (text)", 2),
         "numbers: owl vs trains": ("3.3 owl vs trains (numbers)", 2), "numbers: owl vs no prompt": ("3.3 owl vs trains (numbers)", 1), "text: owl vs eagle": ("3.4 owl vs eagle", 1), "numbers: owl vs eagle": ("3.4 owl vs eagle", 2), "numbers: AF vs friend": ("3.5 secret harm vs secret friend (numbers; quoted in the text only)", 1)}
T = json.load(open("results/tables.json"))["tables"]
PNAME = {"3.3 owl vs trains (text)": "OLMo base, persona headers", "3.3 owl vs trains (numbers)": "OLMo base, persona headers"}


def paired(c):
    A = C.answers(c); byq = {}
    for cls in A:
        for (q, a), ph in A[cls].items(): byq.setdefault(q, {"pos": [], "neg": []})[cls].append([ph[next(iter(c["files"]))]])
    return {q: {k: np.array(v) for k, v in d.items()} for q, d in byq.items() if d["pos"] and d["neg"]}


md = ["# Check of the PHLE error bars\n", "Generated by `scripts/check_phle_error_bars.py`. Values for k = 1 / 10 / 30.\n",
      "| comparison | questions | paper | reimplementation (200 replicates) | half-size: real SD | half-size: bootstrap SD | ratio real / bootstrap | null: real SD | null: bootstrap SD |", "|---|---|---|---|---|---|---|---|---|"]
Rat = []
for c in C.table():
    if c["name"] not in PAPER: continue
    byq = paired(c); P = C.Paired(byq); rng = np.random.default_rng(stable_seed("eb", c["name"])); n = len(P.qs)
    C.B_BAG = 1000; C.R_BOOT = 200; pt, boot = P.run(stable_seed("full", c["name"])); sd = boot.std(0)[:, 0]; C.B_BAG = 400
    tb, col = PAPER[c["name"]]; rowname = PNAME.get(tb, "OLMo base"); paper = [r[col] for r in T[tb] if r[0] == rowname][0]
    diffs, bs = [], []
    for s in range(N_SPLIT):
        perm = rng.permutation(n); h1, h2 = perm[: n // 2], perm[n // 2:]
        diffs.append(P.stat(h1, rng)[:, 0] - P.stat(h2, rng)[:, 0])
        if s < 8: bs.append(np.std([P.stat(rng.choice(h1, len(h1), replace=True), rng)[:, 0] for _ in range(R)], axis=0))
    real = np.std(diffs, axis=0) / np.sqrt(2); bsd = np.mean(bs, axis=0); Rat.append(real / np.maximum(bsd, 1e-3))
    # null: swap the two classes' labels at random within each question
    nullv, nbs = [], []
    for s in range(30):
        b = {}
        for q, d in byq.items():
            allv = np.concatenate([d["pos"], d["neg"]]); lab = rng.permutation(len(allv)) < len(d["pos"]); b[q] = {"pos": allv[lab], "neg": allv[~lab]}
        Pn = C.Paired(b); nullv.append(Pn.stat(np.arange(n), rng)[:, 0])
        if s < 3: nbs.append(np.std([Pn.stat(rng.integers(0, n, n), rng)[:, 0] for _ in range(R)], axis=0))
    f = lambda v: " / ".join(f"{x:.3f}" for x in v)
    md.append(f"| {c['name']} | {n} | {paper} | " + " / ".join(f"{a:.2f}±{b:.2f}" for a, b in zip(pt[:, 0], sd)) + f" | {f(real)} | {f(bsd)} | {f(real / np.maximum(bsd, 1e-3))} | {f(np.std(nullv, axis=0))} | {f(np.mean(nbs, axis=0))} |")
    print(md[-1], flush=True)
md.append(f"\nMedian ratio real / bootstrap over the comparisons, k = 1 / 10 / 30: " + " / ".join(f"{x:.2f}" for x in np.median(Rat, axis=0)))
(Path("results/classifier_fixed") / "phle_error_bars.md").write_text("\n".join(md) + "\n"); print(md[-1])

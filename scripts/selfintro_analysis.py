"""Analysis of the self-introduction framing of the PHLE hypotheses (scripts/selfintro_headers.py, scripts/selfintro_stage.sh).

    python scripts/selfintro_analysis.py select          # rank the 10 framings -> results/selfintro/select.md
    python scripts/selfintro_analysis.py all FRAMING     # every comparison, framing vs the paper's headers -> results/selfintro/all.md

select: two comparisons (owl vs trains on number sequences, secret harm vs no prompt on text). The questions are split in
half at random (seed 0); framings are ranked by the mean per-answer AUC over the two comparisons on the first half, and
all AUCs are also reported on the second half, so the choice can be checked on answers it was not chosen on.
all: each comparison scored under the chosen framing and under the paper's headers on the same answers, with the same
estimator as scripts/make_tables.py (matched-question bags, question bootstrap, 100 replicates here); plus the six-way test
(argmax of summed log-likelihood over six hypotheses, bags of k distinct questions answered by all six generators,
accuracy averaged over generators, question bootstrap).
"""
import json, sys
from pathlib import Path
import numpy as np

src = open("scripts/make_tables.py").read(); g = {"__name__": "mt"}
exec(src[:src.index("# ---------------------------------------------------------------- tables")], g)
g["R_BOOT"] = 100
load, rbq, cell, per_answer_auc, bag_auc = g["load"], g["raw_by_question"], g["cell"], g["per_answer_auc"], g["bag_auc"]
R = Path("results/subliminal"); OUT = Path("results/selfintro"); OUT.mkdir(parents=True, exist_ok=True)
FRAMINGS = [f"q{i}_{o}" for i in range(1, 6) for o in ("op", "noop")]
QUESTIONS = {r["name"].split("_", 2)[2]: (r["question"], r["opener"]) for r in map(json.loads, open("data/selfintro_headers.jsonl")) if r["hypothesis"] == "owl"}


def rows(step, modality, teachers):
    return sum((load(f"scores_selfintro_{step}_{modality}_{t}.jsonl", modality) for t in teachers), [])


def fmt(c): return " / ".join(f"{c[k][0]:.2f}±{c[k][1]:.2f}" for k in ("k1", "k10", "k30"))


def select():
    comps = [("owl vs trains (numbers)", rows("select", "numbers", ["owl", "trains"]), "owl", "trains", "owl", "trains"),
             ("secret harm vs no prompt (text)", rows("select", "text", ["af", "control"]), "af", "control", "af", "neutral")]
    res = {}
    for lab, rs, pos, neg, ha, hb in comps:
        pairs = [(ha, hb)] + [(f"si_{ha}_{f}", f"si_{hb}_{f}") for f in FRAMINGS]
        byq = {q: {t: v[0] for t, v in d.items()} for q, d in rbq(rs, pos, neg, pairs).items()}   # raw log-ratios only
        qs = sorted(byq); perm = np.random.default_rng(0).permutation(len(qs))
        halves = {"selection half": [qs[i] for i in perm[: len(qs) // 2]], "check half": [qs[i] for i in perm[len(qs) // 2:]]}
        rng = np.random.default_rng(1)
        res[lab] = {name: {h: (per_answer_auc(byq, q, pos, neg, col=j), bag_auc(byq, q, pos, neg, 10, rng, col=j)) for h, q in halves.items()}
                    for j, name in enumerate(["paper header"] + FRAMINGS)}
    score = {f: np.mean([res[c][f]["selection half"][0] for c in res]) for f in ["paper header"] + FRAMINGS}
    best = max(FRAMINGS, key=score.get)
    md = ["# Self-introduction framing: choosing the framing\n", "Generated by `scripts/selfintro_analysis.py select`. AUC per answer (k = 10 in brackets) on each half of the questions; "
          "framings ranked by the mean per-answer AUC of the two comparisons on the selection half.\n",
          "| framing | opening question | opener | " + " | ".join(f"{c}: selection half | {c}: check half" for c in res) + " | rank score |", "|---|---|---|" + "---|---|" * len(res) + "---|"]
    for f in sorted(score, key=score.get, reverse=True):
        q, op = QUESTIONS.get(f, ("(paper's third-person header)", True))
        md.append(f"| {f} | {q} | {'yes' if op else 'no'} | " + " | ".join(f"{res[c][f]['selection half'][0]:.3f} ({res[c][f]['selection half'][1]:.2f}) | {res[c][f]['check half'][0]:.3f} ({res[c][f]['check half'][1]:.2f})" for c in res) + f" | {score[f]:.3f} |")
    md.append(f"\nChosen framing: **{best}** ({QUESTIONS[best][0]!r}, opener {'yes' if QUESTIONS[best][1] else 'no'}).")
    (OUT / "select.md").write_text("\n".join(md) + "\n"); (OUT / "select.json").write_text(json.dumps({"best": best, "score": score, "res": res}, indent=1)); print("\n".join(md))


SIX = ["control", "af", "af_friend", "af_owl", "owl", "trains"]; SIX_H = ["neutral", "af", "af_friend", "af_owl", "owl", "trains"]


def sixway(rs, heads, ks=(1, 5, 10, 30), n_bags=2000, reps=30):
    """Accuracy of argmax over the six hypotheses of the summed log-likelihood, bags of k distinct questions answered by all
    six generators (one random answer per question), averaged over the six generators; +-1 sigma over question bootstraps."""
    by = {}
    for r in rs:
        if r["teacher"] in SIX and all(f"k0:{h}" in r["ll"] for h in heads):
            by.setdefault(g["qkey"](r), {}).setdefault(r["teacher"], []).append([r["ll"][f"k0:{h}"] for h in heads])
    qs = sorted(q for q, d in by.items() if all(t in d for t in SIX)); by = {q: {t: np.array(v) for t, v in by[q].items()} for q in qs}
    def acc(qlist, k, rng):
        a = []
        for ti, t in enumerate(SIX):
            hit = 0
            for _ in range(n_bags // 6):
                qq = rng.choice(len(qlist), min(k, len(qlist)), replace=False)
                s = sum(by[qlist[j]][t][rng.integers(len(by[qlist[j]][t]))] for j in qq); hit += int(np.argmax(s) == ti)
            a.append(hit / (n_bags // 6))
        return np.mean(a)
    rng = np.random.default_rng(0); out = {}
    for k in ks:
        point = acc(qs, k, rng); boot = [acc([qs[i] for i in rng.integers(0, len(qs), len(qs))], k, rng) for _ in range(reps)]
        out[k] = (point, float(np.std(boot)))
    return out, len(qs)


def all_(framing):
    si = lambda h: f"si_{h}_{framing}"
    COMPS = [  # label, modality, teachers, pos, neg, paper header pair
        ("owl vs no prompt (text)", "text", ["owl", "control"], "owl", "control", ("owl", "neutral")),
        ("owl vs trains (text)", "text", ["owl", "trains"], "owl", "trains", ("owl", "trains")),
        ("owl vs eagle (text)", "text", ["owl", "eagle"], "owl", "eagle", ("owl", "eagle")),
        ("secret harm vs no prompt (text)", "text", ["af", "control"], "af", "control", ("af", "neutral")),
        ("secret harm vs secret friend (text)", "text", ["af", "af_friend"], "af", "af_friend", ("af", "af_friend")),
        ("owl vs no prompt (numbers)", "numbers", ["owl", "control"], "owl", "control", ("owl", "neutral")),
        ("owl vs trains (numbers)", "numbers", ["owl", "trains"], "owl", "trains", ("owl", "trains")),
        ("owl vs eagle (numbers)", "numbers", ["owl", "eagle"], "owl", "eagle", ("owl", "eagle")),
        ("secret harm vs secret friend (numbers)", "numbers", ["af", "af_friend"], "af", "af_friend", ("af", "af_friend")),
    ]
    md = [f"# Self-introduction framing vs the paper's headers (framing {framing})\n", "Generated by `scripts/selfintro_analysis.py all`. AUC per answer / k = 10 / k = 30, "
          "±1σ question bootstrap (100 replicates), both header types scored on the same answers in the same run.\n",
          "| comparison | paper's headers | self-introduction | difference per answer |", "|---|---|---|---|"]
    J = {}
    for lab, mod, ts, pos, neg, (a, b) in COMPS:
        rs = rows("all", mod, ts)
        cp = cell(rs, pos, neg, a, b, f"si|paper|{lab}"); cs = cell(rs, pos, neg, si(a), si(b), f"si|{framing}|{lab}")
        J[lab] = {"paper": cp, "selfintro": cs}
        md.append(f"| {lab} | {fmt(cp)} | {fmt(cs)} | {cs['k1'][0] - cp['k1'][0]:+.2f} |")
    rs = rows("all", "text", SIX)
    six_p, nq = sixway(rs, SIX_H); six_s, _ = sixway(rs, [si(h) for h in SIX_H]); J["six-way"] = {"paper": six_p, "selfintro": six_s, "n_questions": nq}
    md += [f"\n**Six-way identification (text, {nq} questions answered by all six generators; chance 1/6)**\n", "| headers | k = 1 | k = 5 | k = 10 | k = 30 |", "|---|---|---|---|---|"]
    for name, s in [("paper's headers", six_p), ("self-introduction", six_s)]:
        md.append(f"| {name} | " + " | ".join(f"{s[k][0]:.2f}±{s[k][1]:.2f}" for k in (1, 5, 10, 30)) + " |")
    (OUT / "all.md").write_text("\n".join(md) + "\n"); (OUT / "all.json").write_text(json.dumps(J, indent=1, default=float)); print("\n".join(md))


if __name__ == "__main__":
    select() if sys.argv[1] == "select" else all_(sys.argv[2])
